const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('src/editor.js','utf8');
const classSource=source.slice(source.indexOf('      class PlanService {'),source.indexOf('      const baseModelYaml ='));
const yamlSource=source.slice(source.indexOf('      class YamlCodec {'),source.indexOf('      class SvgCodec {'));
const context={structuredClone,console, publishPersistentPlan(){}, number:n=>String(n), planService:null};
vm.createContext(context);
vm.runInContext(classSource+'\nthis.PlanService=PlanService;',context);
const service=new context.PlanService({patterns:[{name:'grid',tileWidth:10,tileHeight:10}],walls:[{name:'wall',outline:{points:[[0,0],[100,0],[100,100]],pattern:'grid'},patternRegions:[{x:0,y:0,width:20,height:20,pattern:'grid'}]}]});
context.planService=service;
assert.equal(service.wall('wall').outline.patternRotation,0);
assert.equal(service.wall('wall').patternRegions[0].patternRotation,0);
service.setOutlineValue('wall','patternRotation',37);
service.setPatternRegion('wall',0,'patternRotation',123);
assert.equal(service.snapshot().walls[0].outline.patternRotation,37);
assert.equal(service.snapshot().walls[0].patternRegions[0].patternRotation,123);
vm.runInContext(yamlSource+'\nthis.YamlCodec=YamlCodec;',context);
const yaml=context.YamlCodec.encode(service.snapshot());
const decoded=context.YamlCodec.decode(yaml);
assert.equal(decoded.walls[0].outline.patternRotation,37);
assert.equal(decoded.walls[0].patternRegions[0].patternRotation,123);
console.log('Rotation defaults, mutations, and YAML round trip passed.');
